"""Export the airfield's buildings with their authored geometry and LODs, and place them in the scene.

Usage:
    python export_buildings.py --caldera-root <dir> --game-dir games/CalderaDemo

Writes one <game>/assets/models/airfield/<model>.glb per distinct building, plus
<game>/assets/scripts/airfield_lod.lua, one scene entity per placed building, and
<game>/source/buildings_export_report.json. Entities from an earlier run are replaced.

Geometry is not simplified: every non-guide triangle of the authored modelLod variants is kept, with
its authored normals where it has them. The exception is whole props in Caldera's interior groups,
which are left out because ray tracing cannot fit them on the target GPU; --keep-interior-objects
keeps them. Each .glb has one glTF scene per LOD. Meshes the two LODs
share are stored once, and each part is one vertex-colored primitive, because every model primitive
takes two of the renderer's 1024 materials. The dataset ships no textures and no displayColor values,
so a triangle's color comes from its material's name.

Run without -I: this imports export_terrain from its own folder.
"""
import argparse
import json
import math
from pathlib import Path
import re
import struct
import sys

import numpy as np
from pxr import Sdf, Usd, UsdGeom

import export_terrain as et

DISTRICT_ROOT = '/world/map_airfield'
GROUP_DEPTH = 5  # path parts down to /world/map_airfield/<set>/<object>
MIN_FOOTPRINT = 12.0  # meters; smaller groups are props
MIN_HEIGHT = 3.0
AGGREGATE_FOOTPRINT = 100.0  # meters; a wider group is a neighborhood, so its children are the buildings
# Fences, plants, junk and paved lots are not buildings.
EXCLUDED = re.compile(r'fenc|foliage|(^|_)tree|palm|audio|scrapyard|parking|_ground(_\d+)?$|(^|_)road|sidewalk|garden|^worldspawn')
PROP_INSTANCE = 'misc_model'  # the group that places a prop asset; the next path part names the asset
# Caldera's own interior groups: int_01, side_extension_01_a_int, geo_interior_01.
INTERIOR_GROUP = re.compile(r'(.*_)?int(_\d+[a-z]?|_2floor)?|(.*_)?interior(_\d+)?')
# Assets in those groups that are the building, not an object in it.
STRUCTURE_ASSET = re.compile(r'^building_|wall|floor|ceiling|roof|beam|column|pillar|stair|door|window|frame|girder|truss|support|'
                             r'catwalk|railing|handrail|foundation|slab|ladder|corrug|brick|concrete|elevator')
# Objects whose names read like structure.
FIXTURE_ASSET = re.compile(r'light|lamp|sconce|mounted|clock|mirror|tarp|sidewalk')
LOD_VARIANT_SET = 'modelLod'
FAR_LOD = 1  # authored lod2 and lod3 save under 5% more in this district, for the memory of another copy
MAX_GLB_BYTES = 0xffffffff
MAX_PART_VERTICES = 1500000  # a mesh asset decodes within 256 MiB (ModelAsset.cpp), at 64 bytes a vertex plus indices
SHADE_RANGE = 0.12  # each material varies this much around its bucket, so neighboring parts stay apart
ENTITY_BASE = 1000  # generated entities take free ids from here up
LOD_SCRIPT_NAME = 'airfield_lod'  # marks a generated entity, so anything else in the scene is left alone
NAME_CAPACITY = 63  # kFieldStringCapacity less its terminator
BUCKETS = (
    ('glass', (0.06, 0.08, 0.10), ('glass', 'window')),
    ('roof', (0.13, 0.13, 0.14), ('roof', 'shingle', 'tar')),
    ('metal', (0.22, 0.23, 0.24), ('metal', 'steel', 'corrug', 'iron', 'rust', 'alum', 'pipe', 'tin')),
    ('brick', (0.28, 0.18, 0.15), ('brick',)),
    ('wood', (0.20, 0.16, 0.11), ('wood', 'plank')),
    ('canvas', (0.26, 0.25, 0.18), ('canvas', 'tarp', 'tent', 'fabric', 'cloth')),
    ('concrete', (0.30, 0.29, 0.27), ()),
)
DEFAULT_BUCKET = len(BUCKETS) - 1
LOD_SCRIPT = """-- Generated by tools/caldera_export/export_buildings.py. Picks a building's LOD scene by camera distance.
local Lod = {}

local kDistances = { 300.0 }
local kHysteresis = 0.9 -- moving closer switches this much sooner than moving away, so a border cannot flicker
local kPeriod = 0.25

function Lod.NewInstanceData()
    return { wait = math.random() * kPeriod, lod = 0 }
end

function Lod.OnUpdate(self, world, entity, dt)
    self.wait = self.wait - dt
    if self.wait > 0.0 then
        return
    end
    self.wait = kPeriod
    local camera = world:get_active_camera()
    if camera == nil then
        return
    end
    local a = world:get(camera, "Transform").position
    local b = world:get(entity, "Transform").position
    local dx, dy, dz = a.x - b.x, a.y - b.y, a.z - b.z
    local distance = math.sqrt(dx * dx + dy * dy + dz * dz)
    local lod = self.lod
    while lod < #kDistances and distance > kDistances[lod + 1] do
        lod = lod + 1
    end
    while lod > 0 and distance < kDistances[lod] * kHysteresis do
        lod = lod - 1
    end
    if lod ~= self.lod then
        self.lod = lod
        world:set(entity, "ModelPlayer", "scene", lod)
    end
end

return Lod
"""


def to_engine(points, units):
    return np.stack((points[:, 0], points[:, 2], -points[:, 1]), axis=1) * units


def mesh_prims(stage, root_path):
    root = stage.GetPrimAtPath(root_path)
    for prim in Usd.PrimRange(root, Usd.TraverseInstanceProxies()):
        if prim.GetTypeName() == 'Mesh' and UsdGeom.Imageable(prim).ComputePurpose() != UsdGeom.Tokens.guide:
            mesh = UsdGeom.Mesh(prim)
            points = mesh.GetPointsAttr().Get()
            counts = mesh.GetFaceVertexCountsAttr().Get()
            if points is not None and counts is not None and len(points):
                yield prim, mesh, np.asarray(points, dtype=np.float64), np.asarray(counts)


def find_buildings(stage):
    """Paths of the groups that count as buildings, and of building-sized groups excluded by name."""
    units = UsdGeom.GetStageMetersPerUnit(stage)
    cache = UsdGeom.XformCache(0)
    nodes = {}
    for prim, _, points, _ in mesh_prims(stage, DISTRICT_ROOT):
        xf = np.array(cache.GetLocalToWorldTransform(prim))
        engine = to_engine(points @ xf[:3, :3] + xf[3, :3], units)
        low, high = engine.min(axis=0), engine.max(axis=0)
        parts = str(prim.GetPath()).split('/')
        for depth in range(GROUP_DEPTH, len(parts) + 1):
            key = '/'.join(parts[:depth])
            node = nodes.setdefault(key, {'low': low, 'high': high, 'children': set()})
            node['low'], node['high'] = np.minimum(node['low'], low), np.maximum(node['high'], high)
            if depth > GROUP_DEPTH:
                nodes['/'.join(parts[:depth - 1])]['children'].add(key)

    found, left_out = [], []
    stack = sorted(key for key in nodes if key.count('/') == GROUP_DEPTH - 1)
    while stack:
        key = stack.pop()
        node = nodes[key]
        name = key.rsplit('/', 1)[1]
        size = node['high'] - node['low']
        footprint = max(size[0], size[2])
        if EXCLUDED.search(name):
            if footprint >= MIN_FOOTPRINT and size[1] >= MIN_HEIGHT:
                left_out.append(key)
        elif footprint > AGGREGATE_FOOTPRINT and node['children']:
            stack.extend(sorted(node['children']))
        elif footprint >= MIN_FOOTPRINT and size[1] >= MIN_HEIGHT:
            found.append(key)
    return sorted(found), left_out


def placement_of(stage, path):
    """(entity position in meters, yaw in degrees), or None when it is not upright at unit scale."""
    xf = np.array(UsdGeom.XformCache(0).GetLocalToWorldTransform(stage.GetPrimAtPath(path)))
    rotation = xf[:3, :3]
    if np.abs(np.linalg.norm(rotation, axis=1) - 1.0).max() > 1e-3 or abs(rotation[2, 2] - 1.0) > 1e-3:
        return None
    units = UsdGeom.GetStageMetersPerUnit(stage)
    position = to_engine(xf[3, :3][None], units)[0]
    return position, math.degrees(math.atan2(rotation[0, 1], rotation[0, 0]))


def select_authored_lod(stage, level):
    """Every modelLod variant set to its level-th variant, or its last when it has fewer."""
    wanted = []
    for prim in Usd.PrimRange(stage.GetPseudoRoot()):
        sets = prim.GetVariantSets()
        if LOD_VARIANT_SET in sets.GetNames():
            variants = sets.GetVariantSet(LOD_VARIANT_SET)
            names = sorted(variants.GetVariantNames())
            name = names[min(level, len(names) - 1)]
            if variants.GetVariantSelection() != name:
                wanted.append((prim.GetPath(), name))
    layer = stage.GetSessionLayer()
    with Sdf.ChangeBlock():
        for path, name in wanted:
            Sdf.CreatePrimInLayer(layer, path).variantSelections[LOD_VARIANT_SET] = name
    return len(wanted)


def bucket_of(material):
    material = material.lower()
    for index, (_, _, keys) in enumerate(BUCKETS):
        if any(key in material for key in keys):
            return index
    return DEFAULT_BUCKET


def color_of(material):
    """A bucket's color, shaded by the name's hash so the same material always matches."""
    shade = 1.0 + SHADE_RANGE * (int(et.fnv1a64(material.encode())[:4], 16) / 0xffff * 2.0 - 1.0)
    return tuple(c * shade for c in BUCKETS[bucket_of(material)][1])


def read_mesh(prim, mesh, points, counts, inverse, units):
    """One mesh in the building's frame, welded: positions, normals, colors and triangle indices."""
    xf = np.array(UsdGeom.XformCache(0).GetLocalToWorldTransform(prim)) @ inverse
    rotation = xf[:3, :3]
    engine = to_engine(points @ rotation + xf[3, :3], units)
    indices = np.asarray(mesh.GetFaceVertexIndicesAttr().Get())
    starts = np.concatenate(([0], np.cumsum(counts)[:-1]))

    corners, faces = [], []
    for n in np.unique(counts):
        if n < 3:
            continue
        chosen = np.nonzero(counts == n)[0]
        first = starts[chosen]
        for k in range(1, n - 1):
            corners.append(np.stack((first, first + k, first + k + 1), axis=1))
            faces.append(chosen)
    if not corners:
        return None
    corners = np.concatenate(corners)
    faces = np.concatenate(faces)
    # A mirrored transform or a left-handed mesh winds the other way; the axis change does not.
    if (mesh.GetOrientationAttr().Get() == UsdGeom.Tokens.leftHanded) != (np.linalg.det(rotation) < 0.0):
        corners = corners[:, [0, 2, 1]]

    triangles = engine[indices[corners]]
    cross = np.cross(triangles[:, 1] - triangles[:, 0], triangles[:, 2] - triangles[:, 0])
    length = np.linalg.norm(cross, axis=1)
    solid = length > 1e-12
    if not solid.any():
        return None
    corners, faces, cross, length = corners[solid], faces[solid], cross[solid], length[solid]

    # By name, in a fixed order, so the colors and the output bytes do not depend on subset order.
    subsets = sorted(UsdGeom.Subset.GetAllGeomSubsets(mesh), key=lambda s: s.GetPrim().GetName())
    palette = [BUCKETS[DEFAULT_BUCKET][1]]
    face_color = np.zeros(len(counts), dtype=np.int64)
    for subset in subsets:
        palette.append(color_of(subset.GetPrim().GetName()))
        face_color[np.asarray(subset.GetIndicesAttr().Get())] = len(palette) - 1
    color_ids = np.repeat(face_color[faces], 3)

    normals = None
    primvar = UsdGeom.PrimvarsAPI(prim).GetPrimvar('normals')
    if primvar and primvar.HasValue():
        flat = primvar.ComputeFlattened()
        interpolation = primvar.GetInterpolation()
        if flat is not None and interpolation == UsdGeom.Tokens.faceVarying and len(flat) == len(indices):
            normals = np.asarray(flat, dtype=np.float64)[corners.ravel()]
        elif flat is not None and interpolation == UsdGeom.Tokens.vertex and len(flat) == len(points):
            normals = np.asarray(flat, dtype=np.float64)[indices[corners.ravel()]]
    if normals is not None:
        normals = to_engine(normals @ rotation, 1.0)
        size = np.linalg.norm(normals, axis=1, keepdims=True)
        if (size < 1e-9).any():
            normals = None
        else:
            normals /= size
    if normals is None:
        normals = np.repeat(cross / length[:, None], 3, axis=0)

    # Corners with the same point, color and normal to about half a degree are one vertex.
    point_ids = indices[corners.ravel()].astype(np.int64)
    quantized = np.clip(np.round((normals + 1.0) * 255.5).astype(np.int64), 0, 511)
    keys = (point_ids << 37) | (color_ids << 27) | (quantized[:, 0] << 18) | (quantized[:, 1] << 9) | quantized[:, 2]
    _, first_corner, inverse_corner = np.unique(keys, return_index=True, return_inverse=True)
    return {
        'positions': engine[point_ids[first_corner]].astype('<f4'),
        'normals': normals[first_corner].astype('<f4'),
        'colors': np.array(palette, dtype='<f4')[color_ids[first_corner]],
        'indices': inverse_corner.ravel().astype('<u4'),
    }


def is_interior_object(relative_path):
    """Whether a mesh, by its path under the building, is a prop placed in an authored interior group."""
    parts = relative_path.strip('/').split('/')
    instance = next((i for i, part in enumerate(parts) if part.startswith(PROP_INSTANCE)), None)
    if instance is None or instance + 1 >= len(parts):
        return False
    if not any(INTERIOR_GROUP.fullmatch(group.lower()) for group in parts[:instance]):
        return False
    asset = parts[instance + 1].lower()
    return bool(FIXTURE_ASSET.search(asset)) or not STRUCTURE_ASSET.search(asset)


def read_building(stage, path, keep_interior_objects=True):
    """Each mesh of a building, by its path under the building, as (triangles, points) and its reader."""
    units = UsdGeom.GetStageMetersPerUnit(stage)
    inverse = np.linalg.inv(np.array(UsdGeom.XformCache(0).GetLocalToWorldTransform(stage.GetPrimAtPath(path))))
    parts = {}
    for prim, mesh, points, counts in mesh_prims(stage, path):
        key = str(prim.GetPath())[len(path):]
        if not keep_interior_objects and is_interior_object(key):
            continue
        size = (int((counts - 2).sum()), len(points))
        parts[key] = (size, (prim, mesh, points, counts, inverse, units))
    return parts


def merge(meshes):
    """Meshes concatenated into primitives of at most MAX_PART_VERTICES each, splitting only between meshes."""
    meshes = [m for m in meshes if m is not None]
    groups, count = [], 0
    for mesh in meshes:
        if not groups or count + len(mesh['positions']) > MAX_PART_VERTICES:
            groups.append([])
            count = 0
        groups[-1].append(mesh)
        count += len(mesh['positions'])
    merged = []
    for group in groups:
        offsets = np.cumsum([0] + [len(m['positions']) for m in group[:-1]])
        merged.append({
            'positions': np.concatenate([m['positions'] for m in group]),
            'normals': np.concatenate([m['normals'] for m in group]),
            'colors': np.concatenate([m['colors'] for m in group]),
            'indices': np.concatenate([m['indices'] + offset for m, offset in zip(group, offsets)]).astype('<u4'),
        })
    return merged


def glb_bytes(shared, near_only, far_only):
    """Two scenes, near and far, each drawing the shared part plus its own; color lives in the vertices."""
    body = bytearray()
    views, accessors, meshes, nodes = [], [], [], []

    def add_accessor(array, kind, component, target, bounds=False):
        data = array.tobytes()
        views.append({'buffer': 0, 'byteOffset': len(body), 'byteLength': len(data), 'target': target})
        body.extend(data)
        body.extend(b'\0' * (-len(body) % 4))
        accessors.append({'bufferView': len(views) - 1, 'componentType': component, 'count': len(array), 'type': kind})
        if bounds:
            accessors[-1]['min'] = [float(v) for v in array.min(axis=0)]
            accessors[-1]['max'] = [float(v) for v in array.max(axis=0)]
        return len(accessors) - 1

    def add_part(name, parts):
        added = []
        for index, part in enumerate(parts):
            label = name if index == 0 else f'{name}_{index}'
            meshes.append({'name': label, 'primitives': [{
                'attributes': {
                    'POSITION': add_accessor(part['positions'], 'VEC3', 5126, 34962, True),
                    'NORMAL': add_accessor(part['normals'], 'VEC3', 5126, 34962),
                    'COLOR_0': add_accessor(part['colors'], 'VEC3', 5126, 34962),
                },
                'indices': add_accessor(part['indices'], 'SCALAR', 5125, 34963),
                'material': 0,
            }]})
            nodes.append({'name': label, 'mesh': len(meshes) - 1})
            added.append(len(nodes) - 1)
        return added

    shared_nodes = add_part('shared', shared)
    near_nodes = add_part('near', near_only)
    far_nodes = add_part('far', far_only)
    document = {
        'asset': {'version': '2.0', 'generator': 'tools/caldera_export/export_buildings.py'},
        'scene': 0,
        'scenes': [{'name': 'near', 'nodes': shared_nodes + near_nodes}, {'name': 'far', 'nodes': shared_nodes + far_nodes}],
        'nodes': nodes,
        'meshes': meshes,
        # Authored sheets such as roof panels are single-sided surfaces seen from both sides.
        'materials': [{'name': 'building', 'doubleSided': True,
                       'pbrMetallicRoughness': {'baseColorFactor': [1.0, 1.0, 1.0, 1.0], 'metallicFactor': 0.0, 'roughnessFactor': 1.0}}],
        'accessors': accessors,
        'bufferViews': views,
        'buffers': [{'byteLength': len(body)}],
    }
    text = json.dumps(document, separators=(',', ':'), sort_keys=True).encode()
    text += b' ' * (-len(text) % 4)
    total = 12 + 8 + len(text) + 8 + len(body)
    if total > MAX_GLB_BYTES:
        raise et.ExportError(f'a model needs {total} bytes, past the .glb limit')
    return (struct.pack('<4sII', b'glTF', 2, total) + struct.pack('<I4s', len(text), b'JSON') + text +
            struct.pack('<I4s', len(body), b'BIN\0') + bytes(body))


def export_model(near_stage, far_stage, path, keep_interior_objects=False):
    """(glb bytes, report entry). A mesh unchanged between the stages is shared by both LODs."""
    near = read_building(near_stage, path, keep_interior_objects)
    far = read_building(far_stage, path, keep_interior_objects)
    same = {key for key in near if key in far and near[key][0] == far[key][0]}
    shared = merge([read_mesh(*near[key][1]) for key in sorted(same)])
    near_only = merge([read_mesh(*near[key][1]) for key in sorted(near.keys() - same)])
    far_only = merge([read_mesh(*far[key][1]) for key in sorted(far.keys() - same)])
    if not shared and not near_only:
        raise et.ExportError(f'{path}: no triangles')

    report = {
        'near_triangles': sum(len(p['indices']) // 3 for p in shared + near_only),
        'far_triangles': sum(len(p['indices']) // 3 for p in shared + far_only),
        'stored_triangles': sum(len(p['indices']) // 3 for p in shared + near_only + far_only),
        'stored_vertices': sum(len(p['positions']) for p in shared + near_only + far_only),
        'primitives': len(shared) + len(near_only) + len(far_only),
    }
    return glb_bytes(shared, near_only, far_only), report


def entity_json(entity_id, name, model_name, position, yaw):
    half = math.radians(yaw) / 2.0
    return {
        'components': [
            {'fields': {'position': [float(v) for v in position], 'rotation': [0.0, math.sin(half), 0.0, math.cos(half)], 'scale': [1.0, 1.0, 1.0]}, 'type': 'Transform'},
            {'fields': {'position': [float(v) for v in position]}, 'type': 'WorldTransform'},
            {'fields': {'name': name}, 'type': 'Name'},
            {'fields': {'animationAsset': '', 'clip': 0, 'loop': False, 'modelAsset': '', 'modelName': model_name,
                        'playing': False, 'scene': 0, 'speed': 1.0, 'time': 0.0}, 'type': 'ModelPlayer'},
            {'fields': {'scriptName': LOD_SCRIPT_NAME}, 'type': 'ScriptRef'},
        ],
        'id': entity_id,
        'parent': 0,
    }


def is_generated_entity(path):
    """Whether an entity file carries this exporter's LOD script; a missing file is not one."""
    if not path.exists():
        return False
    components = json.loads(path.read_text())['components']
    return any(c['type'] == 'ScriptRef' and c['fields'].get('scriptName') == LOD_SCRIPT_NAME for c in components)


def write_scene(game_dir, placed):
    """Replaces this exporter's entities in the default scene; other entities are left alone."""
    scene_dir = Path(game_dir) / 'scenes' / 'default'
    manifest_path = scene_dir / 'scene.json'
    manifest = json.loads(manifest_path.read_text())
    kept = []
    for entity_id in manifest['entities']:
        path = scene_dir / 'entities' / f'{entity_id}.json'
        if is_generated_entity(path):
            path.unlink()
        else:
            kept.append(entity_id)
    manifest['entities'] = kept
    taken = set(kept)
    entity_id = ENTITY_BASE - 1
    for name, model_name, position, yaw in placed:
        entity_id += 1
        while entity_id in taken:
            entity_id += 1
        et.write_atomic(scene_dir / 'entities' / f'{entity_id}.json',
                        (json.dumps(entity_json(entity_id, name, model_name, position, yaw), indent=2) + '\n').encode())
        manifest['entities'].append(entity_id)
    manifest['nextId'] = max(manifest['entities'], default=0) + 1
    et.write_atomic(manifest_path, (json.dumps(manifest, indent=2) + '\n').encode())


def model_identity(stage, path):
    """Same counts and the same extent in the building's own frame: the same authored model."""
    units = UsdGeom.GetStageMetersPerUnit(stage)
    cache = UsdGeom.XformCache(0)
    inverse = np.linalg.inv(np.array(cache.GetLocalToWorldTransform(stage.GetPrimAtPath(path))))
    triangles, meshes = 0, 0
    low, high = np.full(3, np.inf), np.full(3, -np.inf)
    for prim, _, points, counts in mesh_prims(stage, path):
        xf = np.array(cache.GetLocalToWorldTransform(prim)) @ inverse
        engine = to_engine(points @ xf[:3, :3] + xf[3, :3], units)
        low, high = np.minimum(low, engine.min(axis=0)), np.maximum(high, engine.max(axis=0))
        triangles += int((counts - 2).sum())
        meshes += 1
    return triangles, meshes, *np.round(low, 1).tolist(), *np.round(high, 1).tolist()


def export(root, game_dir, log=None, keep_interior_objects=False):
    """Run the export; returns the report. Raises ExportError, leaving what is there, on failure."""
    path = Path(root) / et.RUNWAY_LAYER
    if not path.exists():
        raise et.ExportError(f'no airfield district layer at {path}')
    stage = Usd.Stage.Open(str(path), Usd.Stage.LoadAll)
    buildings, left_out = find_buildings(stage)
    if not buildings:
        raise et.ExportError(f'no buildings under {DISTRICT_ROOT}')

    models, placed, tilted = {}, [], []
    for building in buildings:
        placement = placement_of(stage, building)
        if placement is None:
            tilted.append(building)
            continue
        name = building.rsplit('/', 1)[1]
        model = models.setdefault(model_identity(stage, building), {'name': name, 'path': building})
        placed.append((name, model, placement))

    far_stage = Usd.Stage.Open(str(path), Usd.Stage.LoadAll)
    select_authored_lod(far_stage, FAR_LOD)

    # Models are large, so each goes to a temporary name as it is built and replaces the old set at the end.
    model_dir = Path(game_dir) / 'assets' / 'models' / 'airfield'
    staging = Path(game_dir) / 'source' / 'airfield_models.tmp'
    staging.mkdir(parents=True, exist_ok=True)
    # A run that failed left its models here; only this run's may reach assets/.
    for stale in staging.glob('*'):
        stale.unlink()
    used, entries = set(), {}
    for number, model in enumerate(models.values()):
        model_name = model['name'] if model['name'] not in used else f"{model['name']}_{number}"
        used.add(model_name)
        logical = f'models/airfield/{model_name}.glb'
        if len(logical) > NAME_CAPACITY:
            logical = f'models/airfield/b{number:03d}.glb'
        model['logical'] = logical
        data, entries[logical] = export_model(stage, far_stage, model['path'], keep_interior_objects)
        et.write_atomic(staging / Path(logical).name, data)
        if log:
            log(f"{number + 1}/{len(models)} {logical}: {entries[logical]['near_triangles']} near, {entries[logical]['far_triangles']} far, "
                f"{entries[logical]['stored_vertices']} vertices, {len(data) // (1 << 20)} MiB")

    commit = et.caldera_commit(root)
    report = {
        'caldera_commit': commit,
        'caldera_commit_is_pinned': commit == et.PINNED_COMMIT,
        'keep_interior_objects': keep_interior_objects,
        'placed': [{'name': name, 'model': model['logical'], 'position': [float(v) for v in position], 'yaw_degrees': yaw}
                   for name, model, (position, yaw) in placed],
        'models': entries,
        'not_upright': tilted,
        'excluded_by_name': sorted(left_out),
    }
    # The old models go first, so a renamed one leaves nothing behind for the cooker.
    model_dir.mkdir(parents=True, exist_ok=True)
    for old in model_dir.glob('*.glb*'):
        old.unlink()
    for built in staging.glob('*.glb'):
        built.replace(model_dir / built.name)
    staging.rmdir()
    et.write_atomic(Path(game_dir) / 'assets' / 'scripts' / 'airfield_lod.lua', LOD_SCRIPT.encode())
    write_scene(game_dir, [(name, model['logical'], position, yaw) for name, model, (position, yaw) in placed])
    et.write_atomic(Path(game_dir) / 'source' / 'buildings_export_report.json', (json.dumps(report, indent=2, sort_keys=True) + '\n').encode())
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--caldera-root', required=True)
    parser.add_argument('--game-dir', required=True)
    parser.add_argument('--keep-interior-objects', action='store_true')
    args = parser.parse_args()
    try:
        report = export(args.caldera_root, args.game_dir, log=lambda text: print(text, flush=True),
                        keep_interior_objects=args.keep_interior_objects)
    except et.ExportError as e:
        print(f'export failed: {e}', file=sys.stderr)
        return 1
    if not report['caldera_commit_is_pinned']:
        print(f"warning: Caldera is at {report['caldera_commit']}, expected {et.PINNED_COMMIT}", file=sys.stderr)
    print(f"{len(report['placed'])} buildings from {len(report['models'])} models; {len(report['not_upright'])} not upright")
    return 0


if __name__ == '__main__':
    sys.exit(main())
